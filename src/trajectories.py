"""Harvested teacher episodes, read back from disk. One loader, used everywhere.

The data card, the SFT converter and the teacher-forced evaluator all need the
same thing: "the scored episodes for this harvest, and each decision the teacher
made in them". Three private copies of that join would drift in exactly the way
a second prompt template drifts, so it lives here once.

Pure Python on purpose (json + dataclasses): it is a core module, and
tests/test_core_is_light.py holds it to that.

Two facts about tau2 trajectories that everything downstream depends on:

1.  **The first assistant message is not the teacher's.** tau2's orchestrator
    hardcodes "Hi! How can I help you today?" (orchestrator.py,
    DEFAULT_FIRST_AGENT_MESSAGE). Counting it as a teacher reply inflates the
    step count by one per episode — 108 phantom "decisions" on the 2026-09 harvest
    — and would train the student to open every conversation with it for free.
    decision_steps() skips it, and raises if it is ever missing, so a tau2 change
    cannot silently shift every step index by one.

2.  **Each teacher turn is a reply OR a tool call, never both.** tau2's agent
    instruction says so ("You cannot do both at the same time"). One harvested
    message carries both anyway; tau2 executed the tool call, so that is the
    action recorded here and the stray text is dropped.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

from src.runlog import read_records

# tau2 orchestrator.py: DEFAULT_FIRST_AGENT_MESSAGE. Not generated by any model.
TAU2_GREETING = "Hi! How can I help you today?"

# A user-simulator turn longer than this is a degenerate generation, not a
# customer. Measured 2026-09-22 over 462 scored episodes: normal user turns
# peak at 4,612 characters; 5 baseline episodes (tasks 3, 19, 23, 95, 102) hold
# a single turn of 368k-492k characters, the simulator repeating one sentence
# until it hit its output limit. Two of those five still scored reward 1.0.
DEGENERATE_USER_CHARS = 20_000


@dataclass(frozen=True)
class ToolCall:
    name: str
    arguments: Mapping[str, Any]


@dataclass(frozen=True)
class Action:
    """What the agent did at one decision point."""

    kind: Literal["tool_call", "reply"]
    calls: tuple[ToolCall, ...] = ()
    text: str = ""

    def __post_init__(self) -> None:
        if self.kind == "tool_call" and not self.calls:
            raise ValueError("a tool_call action needs at least one call")
        if self.kind == "reply" and self.calls:
            raise ValueError("a reply action carries no calls")


@dataclass(frozen=True)
class Step:
    """One teacher decision: the conversation so far, and what came next.

    `context` is every message before the decision, exactly as stored, greeting
    included — the greeting is part of what the teacher saw, it just is not
    something the teacher chose.
    """

    index: int  # position of the decision in Episode.messages
    context: tuple[Mapping[str, Any], ...]
    action: Action


@dataclass(frozen=True)
class Episode:
    task_id: str
    rep: int  # RunLog "seed" column: the harvest variant, not an RNG seed
    temperature: float | None
    reward: float
    trajectory_file: str
    messages: tuple[Mapping[str, Any], ...] = field(repr=False)


def load_episodes(
    log_path: str | Path,
    *,
    fingerprint: str,
    successful_only: bool = True,
) -> list[Episode]:
    """Scored episodes logged under `fingerprint`, joined to their trajectories.

    `fingerprint` is required, not defaulted: a log holds records from earlier
    configs too (harvest-harvest.jsonl carries 8 from a superseded judge), and
    mixing them in is how a training set quietly acquires a second teacher.

    successful_only=True is the plan's rejection-sampling rule (§6, week 1):
    only reward 1.0 episodes become training data.
    """
    records = [
        r
        for r in read_records(log_path)
        if r.get("config_fingerprint") == fingerprint and not r.get("smoke")
    ]
    if successful_only:
        records = [r for r in records if r.get("reward") == 1.0]

    by_file: dict[str, list[dict[str, Any]]] = {}
    for r in records:
        by_file.setdefault(r["trajectory_file"], []).append(r)

    episodes: list[Episode] = []
    for path, recs in sorted(by_file.items()):
        sims = _scored_simulations(path)
        for r in recs:
            tid = str(r["task_id"])
            if tid not in sims:
                raise ValueError(f"{path} has no scored simulation for task {tid}")
            episodes.append(
                Episode(
                    task_id=tid,
                    rep=int(r["seed"]),
                    temperature=r.get("temperature"),
                    reward=float(r["reward"]),
                    trajectory_file=path,
                    messages=tuple(sims[tid]["messages"]),
                )
            )
    episodes.sort(key=lambda e: (e.task_id, e.rep))
    return episodes


def _scored_simulations(path: str | Path) -> dict[str, dict[str, Any]]:
    """task_id -> the one scored simulation for it in a tau2 batch file."""
    data = json.loads(Path(path).read_text())
    scored: dict[str, dict[str, Any]] = {}
    for sim in data["simulations"]:
        if sim.get("reward_info") is None:
            continue  # INFRASTRUCTURE_ERROR: never logged, never an episode
        tid = str(sim["task_id"])
        if tid in scored:
            raise ValueError(f"{path} holds two scored simulations for task {tid}")
        scored[tid] = sim
    return scored


def parse_action(message: Mapping[str, Any]) -> Action:
    """An assistant message -> the action it represents. See module note 2."""
    raw_calls = message.get("tool_calls") or []
    if raw_calls:
        calls = tuple(
            ToolCall(name=str(c["name"]), arguments=dict(c.get("arguments") or {}))
            for c in raw_calls
        )
        return Action(kind="tool_call", calls=calls)
    text = (message.get("content") or "").strip()
    if not text:
        raise ValueError(f"assistant message at turn {message.get('turn_idx')} is empty")
    return Action(kind="reply", text=text)


def decision_steps(messages: Sequence[Mapping[str, Any]]) -> list[Step]:
    """Every teacher decision in an episode, greeting excluded. See module note 1."""
    if not messages:
        return []
    first = messages[0]
    if first.get("role") != "assistant" or (first.get("content") or "") != TAU2_GREETING:
        raise ValueError(
            "episode does not open with tau2's hardcoded greeting; "
            "step indexing would be off by one — check the tau2 version"
        )
    return [
        Step(index=i, context=tuple(messages[:i]), action=parse_action(m))
        for i, m in enumerate(messages)
        if i > 0 and m.get("role") == "assistant"
    ]


def all_steps(episodes: Iterable[Episode]) -> list[tuple[Episode, Step]]:
    return [(ep, step) for ep in episodes for step in decision_steps(ep.messages)]


def has_degenerate_user_turn(episode: Episode, limit: int = DEGENERATE_USER_CHARS) -> bool:
    """True if the simulator produced a runaway turn. See DEGENERATE_USER_CHARS.

    Such an episode cannot be replayed in teacher-forced eval (one prompt reaches
    ~125k tokens, four times Qwen2.5's context), and its later states are not a
    customer conversation anyone would deploy against.
    """
    return any(
        m.get("role") == "user" and len(m.get("content") or "") > limit for m in episode.messages
    )
